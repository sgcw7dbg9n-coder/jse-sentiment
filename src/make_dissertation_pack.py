def methods_record(settings: dict) -> None:
    m, f, g = settings["modelling"], settings["features"], settings["gdelt"]
    def cell(pattern: str | None) -> str:
        # A bare | inside a regex would end the markdown cell
        return f"`{pattern}`".replace("|", "\\|") if pattern else "none"

    companies = "\n".join(f"| {c['name']} | {c['ticker']} | {c['sector']} | {cell(c['pattern'])} | {cell(c.get('exclude'))} |"
                          for c in settings["companies"])
    grids = "\n".join(f"| {MODELS[k]} | {', '.join(f'{p}: {v}' for p, v in grid.items())} |" for k, grid in m["grids"].items())
    text = f"""# Method record

Every setting the pipeline used, taken from config/settings.yaml.

## Study design
- Study period: {settings['study_period']['start']} to {settings['study_period']['end']}
- Prices collected: {settings['prices']['start']} to {settings['prices']['end']} (yfinance, adjusted, quoted in cents)
- Market proxy: {settings['market_proxy']['name']} ({settings['market_proxy']['ticker']})
- Training and tuning: sessions up to {m['train_end']}; test: every session after it, used once
- News timing: headlines at or after {settings['market']['close_time']} {settings['market']['timezone']} time, or on non-trading days, count for the next session

## News data
- Source: GDELT Global Knowledge Graph via BigQuery ({g['query']}); company named in the headline
- South African outlets: domains ending in {', '.join(g['sa_domain_suffixes'])}, plus {', '.join(g['sa_extra_domains'])}
- Syndicated copies merged: same company, session and headline text

## Companies
| Company | Ticker | Sector | Headline pattern | Excluded headlines |
| --- | --- | --- | --- | --- |
{companies}

## Sentiment scorers
- VADER compound score
- FinBERT ({settings['sentiment']['finbert_model']}): P(positive) minus P(negative)
- Loughran-McDonald ({Path(settings['sentiment']['lm_dictionary']).name}): (positive - negative) / (positive + negative) words
- GDELT V2Tone (article-level, from GDELT)

## Features
- Return lags: {f['return_lags']}; volatility windows: {f['volatility_windows']}; volume window: {f['volume_window']}
- Sentiment rolling windows (headline-weighted): {f['rolling_windows']}
- Target horizons (sessions): {f['horizons']}; primary target: {m['main_target']}
- Baseline features: {', '.join(m['baseline_features'])}

## Models and evaluation
- Cross-validation: {m['cv_splits']} expanding, date-based folds, purge gap equal to the horizon; tuned on ROC-AUC
- Random state: {m['random_state']}
- Feature sets: {', '.join(m['feature_sets'])}
- Sensitivity targets: {', '.join(m['sensitivity_targets'])}
- Comparison: DeLong test (AUC) and McNemar test (accuracy) against the same model on prices only, Holm-adjusted per target
- Robustness: moving-block bootstrap over trading days (5-session blocks, 2,000 replicates); panel OLS with company fixed effects and date-clustered errors; FinBERT terciles

| Model | Grid searched |
| --- | --- |
{grids}
"""
    (OUT / "methods_record.md").write_text(text, encoding="utf-8")


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    settings = load_settings()
    (OUT / "tables").mkdir(parents=True, exist_ok=True)
    (OUT / "figures").mkdir(parents=True, exist_ok=True)

    news = pd.read_parquet(ROOT / "data" / "interim" / "news_scored.parquet")
