"""Collects every result the dissertation reports into reports/dissertation: numbered tables, figures and a summary."""
import json
import logging
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score, roc_curve

from common import ROOT, load_settings

REPORTS = ROOT / "reports"
PROCESSED = ROOT / "data" / "processed"
OUT = REPORTS / "dissertation"

SCORERS = {"vader_score": "VADER", "finbert_score": "FinBERT", "lm_score": "Loughran-McDonald", "gdelt_tone": "GDELT tone"}
FEATURE_SETS = {"baseline": "Prices only (baseline)", "all_sentiment": "+ all four scorers",
                **{k: f"+ {v}" for k, v in SCORERS.items()}}
MODELS = {"logistic_regression": "Logistic regression", "random_forest": "Random forest", "svm_rbf": "SVM (RBF)"}
COLOURS = {"vader_score": "#2a78d6", "finbert_score": "#eb6834", "lm_score": "#1baf7a", "gdelt_tone": "#eda100",
           "all_sentiment": "#e87ba4", "baseline": "#898781"}
GREY, INK, GRID = "#898781", "#0b0b0b", "#e1e0d9"

log = logging.getLogger("dissertation_pack")


def target_label(target: str) -> str:
    horizon = int(target.rsplit("_", 1)[1].rstrip("d"))
    days = "1 session" if horizon == 1 else f"{horizon} sessions"
    return f"Beats Satrix 40, {days}" if "excess" in target else f"Price up, {days}"


def read_csv(name: str) -> pd.DataFrame | None:
    path = REPORTS / name
    if not path.exists():
        log.warning("%s not found; tables that need it are skipped", name)
        return None
    return pd.read_csv(path)


def first_existing(*names: str) -> pd.DataFrame | None:
    for name in names:
        if (REPORTS / name).exists():
            return pd.read_csv(REPORTS / name)
    log.warning("None of %s found", ", ".join(names))
    return None


def style_axes(ax) -> None:
    ax.spines[["top", "right"]].set_visible(False)
    ax.spines[["left", "bottom"]].set_color("#c3c2b7")
    ax.tick_params(colors=GREY, length=0)
    ax.grid(axis="x", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def save_figure(fig, name: str) -> None:
    fig.savefig(OUT / "figures" / f"{name}.png", dpi=300, bbox_inches="tight", facecolor="white")
    plt.close(fig)


class Pack:
    def __init__(self) -> None:
        self.tables: list[tuple[str, str, pd.DataFrame, str]] = []
        self.facts: list[str] = []

    def table(self, number: str, title: str, frame: pd.DataFrame, note: str = "") -> None:
        frame.to_csv(OUT / "tables" / f"table_{number.replace('.', '_')}.csv", index=False)
        self.tables.append((number, title, frame, note))

    def write_html(self) -> None:
        parts = ["<html><head><meta charset='utf-8'><style>body{font-family:'Times New Roman';font-size:12pt}"
                 "table{border-collapse:collapse;margin-bottom:6pt}th,td{border:1px solid #999;padding:3px 6px}"
                 "th{background:#eee}p.note{font-size:10pt;margin-top:0}</style></head><body>"]
        for number, title, frame, note in self.tables:
            parts.append(f"<p><b>Table {number}: {title}</b></p>")
            parts.append(frame.to_html(index=False, border=0, na_rep=""))
            if note:
                parts.append(f"<p class='note'>{note}</p>")
        (OUT / "tables.html").write_text("".join(parts) + "</body></html>", encoding="utf-8")

    def write_summary(self) -> None:
        lines = ["# Key numbers for the dissertation", "", "Generated by src/make_dissertation_pack.py.", ""]
        lines += [f"- {fact}" for fact in self.facts]
        (OUT / "results_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def data_tables(pack: Pack, settings: dict, news: pd.DataFrame, data: pd.DataFrame) -> None:
    names = {c["ticker"]: c["name"] for c in settings["companies"]}
    sectors = {c["ticker"]: c["sector"] for c in settings["companies"]}
    sessions = data["date"].nunique()

    selection = read_csv("sample_selection.csv")
    if selection is not None:
        pack.table("4.1", "Candidate companies and GDELT headline coverage", selection,
                   "The ten companies with the most headline mentions were kept.")

    cleaning = read_csv("news_cleaning_summary.csv")
    if cleaning is not None:
        cleaning = cleaning.rename(columns={"step": "Cleaning step", "rows": "Rows remaining"})
        pack.table("4.2", "Headlines remaining after each cleaning step", cleaning)
        pack.facts.append(f"Cleaning: {cleaning['Rows remaining'].iloc[0]:,} raw GDELT rows became "
                          f"{cleaning['Rows remaining'].iloc[-1]:,} unique headlines.")

    per = (news.groupby("ticker")
           .agg(headlines=("title", "size"), days=("trading_date", "nunique"),
                finbert=("finbert_score", "mean"), vader=("vader_score", "mean"))
           .reindex(list(names)))
    per = pd.DataFrame({
        "Company": [names[t] for t in per.index], "Ticker": per.index, "Sector": [sectors[t] for t in per.index],
        "Headlines": per["headlines"].fillna(0).astype(int),
        "Sessions with news (%)": (100 * per["days"].fillna(0) / sessions).round(1),
        "Mean FinBERT": per["finbert"].round(3), "Mean VADER": per["vader"].round(3),
    }).sort_values("Headlines", ascending=False)
    pack.table("4.3", "Headlines per company, January 2024 to June 2026", per,
               f"{sessions} trading sessions in the study period.")
    pack.facts.append(f"Sample: {len(names)} companies, {sessions} sessions, {len(data):,} company-days, "
                      f"{len(news):,} headlines; {data['has_news'].mean():.1%} of company-days had news.")
    pack.facts.append(f"Most covered: {per['Company'].iloc[0]} ({per['Headlines'].iloc[0]:,} headlines); "
                      f"least: {per['Company'].iloc[-1]} ({per['Headlines'].iloc[-1]:,}).")

    scores = news[list(SCORERS)]
    describe = pd.DataFrame({
        "Scorer": list(SCORERS.values()),
        "Mean": scores.mean().round(3).values, "SD": scores.std().round(3).values,
        "Min": scores.min().round(3).values, "Max": scores.max().round(3).values,
        "Exactly 0 (%)": (100 * (scores == 0).mean()).round(1).values,
    })
    pack.table("4.4", "Descriptive statistics of headline sentiment scores", describe)

    labels = news[["finbert_positive", "finbert_negative", "finbert_neutral"]].idxmax(axis=1).str.removeprefix("finbert_")
    shares = labels.value_counts(normalize=True)
    lm_hit = (news["lm_positive"] + news["lm_negative"] > 0).mean()
    pack.facts.append("FinBERT labels: " + ", ".join(f"{k} {v:.1%}" for k, v in shares.items())
                      + f"; Loughran-McDonald words in {lm_hit:.1%} of headlines; VADER exactly 0 for "
                      f"{(news['vader_score'] == 0).mean():.1%}.")

    corr = scores.corr(method="spearman").round(2)
    corr.index = corr.columns = list(SCORERS.values())
    pack.table("4.5", "Spearman rank correlation between scorers", corr.reset_index(names="Scorer"))
    off = corr.where(~np.eye(len(corr), dtype=bool)).stack()
    pack.facts.append(f"Scorer correlations range from {off.min():.2f} to {off.max():.2f}.")

    targets = [c for c in data.columns if c.startswith("target_")]
    balance = pd.DataFrame({"Target": [target_label(t) for t in targets],
                            "Share of 1s (%)": [round(100 * data[t].mean(), 1) for t in targets]})
    pack.table("4.6", "Class balance of the prediction targets", balance)

    disagree = news[np.sign(news["vader_score"]) * np.sign(news["finbert_score"]) < 0].copy()
    disagree["gap"] = (disagree["vader_score"] - disagree["finbert_score"]).abs()
    examples = disagree.nlargest(10, "gap")[["ticker", "title", "vader_score", "finbert_score", "lm_score"]]
    examples = examples.rename(columns={"ticker": "Ticker", "title": "Headline", "vader_score": "VADER",
                                        "finbert_score": "FinBERT", "lm_score": "LM"}).round(2)
    pack.table("4.7", "Headlines where VADER and FinBERT disagree most", examples)


def model_tables(pack: Pack, settings: dict) -> None:
    main = settings["modelling"]["main_target"]
    results = first_existing("model_results_sensitivity.csv", "model_results.csv")
    tests = first_existing("significance_tests_sensitivity.csv", "significance_tests.csv")
    if results is None or tests is None:
        return

    primary = results[(results["target"] == main) & (results["model"] != "majority_class")]
    auc = (primary.pivot(index="feature_set", columns="model", values="roc_auc")
           .reindex(list(FEATURE_SETS))[list(MODELS)].round(3))
    auc.index = [FEATURE_SETS[i] for i in auc.index]
    auc.columns = [MODELS[c] for c in auc.columns]
    majority = results[(results["target"] == main) & (results["model"] == "majority_class")].iloc[0]
    pack.table("4.8", "Test ROC-AUC, next-session direction (primary target)", auc.reset_index(names="Feature set"),
               f"Test period January to June 2026, {int(majority['test_rows']):,} company-days. 0.5 = no skill.")

    metrics = primary[["model", "feature_set", "accuracy", "precision", "recall", "f1", "roc_auc", "cv_auc", "best_params"]].copy()
    metrics["model"] = metrics["model"].map(MODELS)
    metrics["feature_set"] = metrics["feature_set"].map(FEATURE_SETS)
    metrics = metrics.rename(columns={"model": "Model", "feature_set": "Feature set", "accuracy": "Accuracy",
                                      "precision": "Precision", "recall": "Recall", "f1": "F1", "roc_auc": "Test AUC",
                                      "cv_auc": "CV AUC", "best_params": "Tuned parameters"}).round(3)
    pack.table("4.9", "All test metrics, primary target", metrics,
               f"Majority-class benchmark accuracy: {majority['accuracy']:.3f}.")

    sig = tests[tests["target"] == main][["model", "feature_set", "auc_baseline", "auc_enhanced", "auc_diff",
                                          "delong_p", "delong_p_holm", "mcnemar_p_holm"]].copy()
    sig["model"] = sig["model"].map(MODELS)
    sig["feature_set"] = sig["feature_set"].map(FEATURE_SETS)
    sig = sig.rename(columns={"model": "Model", "feature_set": "Feature set", "auc_baseline": "AUC baseline",
                              "auc_enhanced": "AUC with sentiment", "auc_diff": "Difference",
                              "delong_p": "DeLong p", "delong_p_holm": "DeLong p (Holm)",
                              "mcnemar_p_holm": "McNemar p (Holm)"}).round(3)
    pack.table("4.10", "Sentiment-enhanced vs baseline, primary target", sig,
               "Holm adjustment across the 15 comparisons for this target.")

    aucs = primary["roc_auc"]
    better = (sig["DeLong p (Holm)"] < 0.05) & (sig["Difference"] > 0)
    pack.facts.append(f"Primary result: test AUC {aucs.min():.3f} to {aucs.max():.3f}; majority-class accuracy "
                      f"{majority['accuracy']:.3f}; {int(better.sum())} of {len(sig)} comparisons significantly better "
                      f"after Holm; smallest Holm p = {sig['DeLong p (Holm)'].min():.3f}.")

    boot = read_csv("bootstrap_comparisons.csv")
    other = tests[(tests["target"] != main) & (tests["feature_set"] == "all_sentiment")].copy()
    if not other.empty:
        if boot is not None:
            other = other.merge(boot[boot["sample"] == "all_days"][["target", "model", "feature_set", "auc_ci_low", "auc_ci_high"]],
                                on=["target", "model", "feature_set"], how="left")
        sens = pd.DataFrame({
            "Target": other["target"].map(target_label), "Model": other["model"].map(MODELS),
            "AUC baseline": other["auc_baseline"].round(3), "AUC with sentiment": other["auc_enhanced"].round(3),
            "Difference": other["auc_diff"].round(3),
            "Bootstrap 95% CI": [f"[{lo:+.3f}, {hi:+.3f}]" if pd.notna(lo) else "" for lo, hi in
                                 zip(other.get("auc_ci_low", pd.Series(np.nan, index=other.index)),
                                     other.get("auc_ci_high", pd.Series(np.nan, index=other.index)))],
            "DeLong p (Holm)": other["delong_p_holm"].round(3),
        })
        pack.table("4.11", "Sensitivity analysis: other horizons and market-relative targets", sens,
                   "Baseline vs all four scorers. Holm adjustment within each target.")
        flagged = other[other["delong_p_holm"] < 0.05]
        for row in flagged.itertuples():
            pack.facts.append(f"Significant in sensitivity: {MODELS[row.model]}, {target_label(row.target)}, "
                              f"AUC change {row.auc_diff:+.3f}, Holm p {row.delong_p_holm:.3f}.")

    news_tests = read_csv("significance_tests_newsdays.csv")
    if news_tests is not None:
        nd = news_tests[["model", "feature_set", "auc_baseline", "auc_enhanced", "auc_diff", "delong_p_holm"]].copy()
        nd["model"] = nd["model"].map(MODELS)
        nd["feature_set"] = nd["feature_set"].map(FEATURE_SETS)
        nd = nd.rename(columns={"model": "Model", "feature_set": "Feature set", "auc_baseline": "AUC baseline",
                                "auc_enhanced": "AUC with sentiment", "auc_diff": "Difference",
                                "delong_p_holm": "DeLong p (Holm)"}).round(3)
        pack.table("4.12", "Exploratory: company-days with news only", nd)
        pack.facts.append(f"News days only: AUC change {nd['Difference'].min():+.3f} to {nd['Difference'].max():+.3f}; "
                          f"smallest Holm p {nd['DeLong p (Holm)'].min():.3f}.")

    if boot is not None:
        b = boot[boot["feature_set"] == "all_sentiment"].copy()
        b = pd.DataFrame({
            "Sample": b["sample"].str.replace("_", " "), "Target": b["target"].map(target_label),
            "Model": b["model"].map(MODELS), "AUC gap": b["auc_gap"].round(3),
            "95% CI low": b["auc_ci_low"].round(3), "95% CI high": b["auc_ci_high"].round(3),
            "Bootstrap p (Holm)": b["auc_p_boot_holm"].round(3),
        })
        pack.table("4.13", "Moving-block bootstrap of the AUC gap (all four scorers minus baseline)", b,
                   "Blocks of 5 trading sessions, 2,000 replicates.")


def robustness_tables(pack: Pack) -> None:
    panel = read_csv("panel_regressions.csv")
    if panel is not None:
        p = pd.DataFrame({
            "Return": panel["horizon"].map({"same_day": "Same session", "next_day": "Next session"}),
            "Scorer": panel["score"].map(SCORERS), "% per SD": panel["coef_pct_per_sd"].round(4),
            "Std error": panel["std_err"].round(4), "t": panel["t"].round(2), "p": panel["p"].round(3),
            "p (Holm)": panel["p_holm"].round(3), "N": panel["n"], "R²": panel["r2"].round(3),
        })
        pack.table("4.14", "Panel regressions of returns on standardised sentiment", p,
                   "Company fixed effects, Satrix 40 return control, standard errors clustered by date.")
        best = panel.sort_values("p").iloc[0]
        pack.facts.append(f"Panel regressions: strongest is {SCORERS[best.score]} {best.horizon.replace('_', ' ')}, "
                          f"{best.coef_pct_per_sd:+.3f}% per SD, p = {best.p:.3f}, Holm {best.p_holm:.2f}.")

    terciles = read_csv("finbert_terciles.csv")
    if terciles is not None:
        terciles = terciles.rename(columns={terciles.columns[0]: "FinBERT third"}).round(3)
        pack.table("4.15", "Returns by FinBERT sentiment third, news days", terciles)
        spread = terciles.iloc[-1]
        pack.facts.append(f"FinBERT terciles, positive minus negative: same session {spread['same_day_ret_pct']:+.3f} "
                          f"pp, next session {spread['next_day_ret_pct']:+.3f} pp.")


def appendix_tables(pack: Pack) -> None:
    dictionary = read_csv("feature_dictionary.csv")
    if dictionary is not None:
        pack.table("A.1", "Feature dictionary", dictionary.rename(columns=str.capitalize))
    for name, number in (("scoring_metadata.json", "A.2"), ("modelling_run.json", "A.3")):
        path = REPORTS / name
        if path.exists():
            meta = json.loads(path.read_text(encoding="utf-8"))
            rows = pd.DataFrame({"Setting": list(meta), "Value": [str(v) for v in meta.values()]})
            pack.table(number, f"Run record: {name}", rows)


def figures(settings: dict, news: pd.DataFrame, data: pd.DataFrame) -> None:
    names = {c["ticker"]: c["name"] for c in settings["companies"]}
    main = settings["modelling"]["main_target"]

    counts = news["ticker"].map(names).value_counts().sort_values()
    fig, ax = plt.subplots(figsize=(6.5, 3.6))
    ax.barh(counts.index, counts.values, color=GREY, height=0.55)
    for y, v in enumerate(counts.values):
        ax.text(v, y, f" {v:,}", va="center", fontsize=8, color=INK)
    style_axes(ax)
    ax.set_xlabel("Headlines after cleaning")
    save_figure(fig, "figure_4_1_headlines_per_company")

    monthly = news.set_index("trading_date").resample("MS")["title"].size()
    fig, ax = plt.subplots(figsize=(6.5, 2.8))
    ax.plot(monthly.index, monthly.values, color=COLOURS["vader_score"], linewidth=2)
    style_axes(ax)
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_ylabel("Headlines per month")
    save_figure(fig, "figure_4_2_headlines_per_month")

    fig, axes = plt.subplots(1, 4, figsize=(8, 2.4), layout="constrained")
    for ax, (score, label) in zip(axes, SCORERS.items()):
        ax.hist(news[score], bins=30, color=COLOURS[score])
        ax.set_title(label, fontsize=9)
        style_axes(ax)
        ax.set_yticks([])
    fig.supylabel("Headlines", fontsize=9)
    save_figure(fig, "figure_4_3_score_distributions")

    corr = news[list(SCORERS)].corr(method="spearman")
    fig, ax = plt.subplots(figsize=(4.4, 3.8))
    image = ax.imshow(corr, cmap="RdBu", vmin=-1, vmax=1)
    ax.set_xticks(range(4), SCORERS.values(), rotation=30, ha="right", fontsize=8)
    ax.set_yticks(range(4), SCORERS.values(), fontsize=8)
    for i in range(4):
        for j in range(4):
            ax.text(j, i, f"{corr.iloc[i, j]:.2f}", ha="center", va="center", fontsize=8,
                    color="white" if abs(corr.iloc[i, j]) > 0.6 else INK)
    fig.colorbar(image, ax=ax, shrink=0.8)
    save_figure(fig, "figure_4_4_scorer_correlations")

    results = first_existing("model_results_sensitivity.csv", "model_results.csv")
    if results is not None:
        primary = results[(results["target"] == main) & (results["model"] != "majority_class")]
        fig, axes = plt.subplots(1, 3, figsize=(8, 3), sharey=True, sharex=True, layout="constrained")
        sets = [s for s in FEATURE_SETS if s in set(primary["feature_set"])]
        for ax, (model, label) in zip(axes, MODELS.items()):
            rows = primary[primary["model"] == model].set_index("feature_set").reindex(sets)
            ax.scatter(rows["roc_auc"], range(len(sets)), c=[COLOURS[s] for s in sets], s=45, zorder=3)
            ax.axvline(0.5, color="#c3c2b7", linewidth=1)
            ax.set_title(label, fontsize=9)
            style_axes(ax)
        reach = max(0.03, (primary["roc_auc"] - 0.5).abs().max() + 0.01)
        axes[0].set_xlim(0.5 - reach, 0.5 + reach)
        axes[0].set_yticks(range(len(sets)), [FEATURE_SETS[s] for s in sets], fontsize=8)
        axes[0].invert_yaxis()
        fig.supxlabel("Test ROC-AUC (0.5 = no skill)", fontsize=9)
        save_figure(fig, "figure_4_5_test_auc")

    boot = read_csv("bootstrap_comparisons.csv")
    if boot is not None:
        b = boot[(boot["feature_set"] == "all_sentiment") & (boot["sample"] == "all_days")].copy()
        b["label"] = b["target"].map(target_label) + " · " + b["model"].map(MODELS)
        b = b.sort_values(["target", "model"]).reset_index(drop=True)
        fig, ax = plt.subplots(figsize=(6.5, 0.32 * len(b) + 1))
        y = np.arange(len(b))
        ax.errorbar(b["auc_gap"], y, xerr=[b["auc_gap"] - b["auc_ci_low"], b["auc_ci_high"] - b["auc_gap"]],
                    fmt="o", color=COLOURS["all_sentiment"], ecolor=COLOURS["all_sentiment"], elinewidth=1.5, ms=5)
        ax.axvline(0, color="#c3c2b7", linewidth=1)
        ax.set_yticks(y, b["label"], fontsize=7)
        ax.invert_yaxis()
        style_axes(ax)
        ax.set_xlabel("Change in test AUC from adding sentiment (95% block-bootstrap CI)")
        save_figure(fig, "figure_4_6_auc_gap_bootstrap")

    predictions_path = next((p for p in (PROCESSED / "test_predictions_sensitivity.parquet",
                                         PROCESSED / "test_predictions.parquet") if p.exists()), None)
    if predictions_path is not None:
        preds = pd.read_parquet(predictions_path)
        preds = preds[preds["target"] == main]
        fig, axes = plt.subplots(1, 3, figsize=(8, 2.9), sharey=True, layout="constrained")
        for ax, (model, label) in zip(axes, MODELS.items()):
            for key in ("baseline", "all_sentiment"):
                part = preds[(preds["model"] == model) & (preds["feature_set"] == key)]
                if part.empty:
                    continue
                fpr, tpr, _ = roc_curve(part["y_true"], part["score"])
                ax.plot(fpr, tpr, color=COLOURS[key], linewidth=1.8,
                        label=f"{FEATURE_SETS[key]} ({roc_auc_score(part['y_true'], part['score']):.3f})")
            ax.plot([0, 1], [0, 1], color="#c3c2b7", linewidth=1)
            ax.set_title(label, fontsize=9)
            ax.legend(fontsize=6, frameon=False, loc="lower right")
            style_axes(ax)
        fig.supxlabel("False positive rate", fontsize=9)
        axes[0].set_ylabel("True positive rate", fontsize=9)
        save_figure(fig, "figure_4_7_roc_curves")

    panel = read_csv("panel_regressions.csv")
    if panel is not None:
        fig, axes = plt.subplots(1, 2, figsize=(7, 2.6), sharey=True, sharex=True, layout="constrained")
        for ax, horizon, title in zip(axes, ("same_day", "next_day"), ("Same session", "Next session")):
            rows = panel[panel["horizon"] == horizon].set_index("score").reindex(list(SCORERS))
            y = np.arange(len(rows))
            for i, (score, row) in enumerate(rows.iterrows()):
                ax.errorbar(row["coef_pct_per_sd"], i, xerr=1.96 * row["std_err"], fmt="o",
                            color=COLOURS[score], elinewidth=1.5, ms=5)
            ax.axvline(0, color="#c3c2b7", linewidth=1)
            ax.set_title(title, fontsize=9)
            style_axes(ax)
        axes[0].set_yticks(y, list(SCORERS.values()), fontsize=8)
        axes[0].invert_yaxis()
        fig.supxlabel("Return (%) per 1 SD of sentiment, with 95% CI", fontsize=9)
        save_figure(fig, "figure_4_8_panel_regressions")

    terciles = read_csv("finbert_terciles.csv")
    if terciles is not None:
        terciles = terciles.set_index(terciles.columns[0]).loc[["negative", "neutral", "positive"]]
        fig, axes = plt.subplots(1, 2, figsize=(7, 2.4), sharey=True, sharex=True, layout="constrained")
        for ax, column, title in zip(axes, ("same_day_ret_pct", "next_day_ret_pct"), ("Same session", "Next session")):
            ax.barh([f"{t.capitalize()} third" for t in terciles.index], terciles[column],
                    color=COLOURS["finbert_score"], height=0.45)
            ax.axvline(0, color="#c3c2b7", linewidth=1)
            ax.set_title(title, fontsize=9)
            style_axes(ax)
        axes[0].invert_yaxis()
